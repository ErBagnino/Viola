#!/usr/bin/env node
// Builds, for copy-paste into the Supabase SQL Editor (no CLI needed):
//  - supabase/setup.sql  = all migrations + seed (new projects)
//  - supabase/update.sql = only the migrations added after the first release
//    (projects created with an older setup.sql). Every one of them is written
//    to be safe to run more than once.
// Run: npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
export function buildSetupSql() {
  const dir = path.join(root, "supabase", "migrations");
  const parts = [
    "-- =====================================================================",
    "-- Vio ♡ — COMPLETE DATABASE SETUP (generated by `npm run db:bundle`)",
    "-- Paste everything into Supabase → SQL Editor → Run. Run it ONCE on a",
    "-- new project. Do not edit by hand: edit supabase/migrations instead.",
    "-- =====================================================================",
    "",
  ];
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".sql")).sort()) {
    parts.push(`-- ---------------------------------------------------------------------`, `-- ${f}`, `-- ---------------------------------------------------------------------`, readFileSync(path.join(dir, f), "utf8").trim(), "");
  }
  parts.push("-- ---------------------------------------------------------------------", "-- seed.sql (starter content)", "-- ---------------------------------------------------------------------", readFileSync(path.join(root, "supabase", "seed.sql"), "utf8").trim(), "");
  return parts.join("\n");
}

/** Migrations after the first public release (20260927000003). */
export const FIRST_RELEASE = "20260927000003";

export function buildUpdateSql() {
  const dir = path.join(root, "supabase", "migrations");
  const files = readdirSync(dir).filter((f) => f.endsWith(".sql") && f.slice(0, 14) > FIRST_RELEASE).sort();
  const parts = [
    "-- =====================================================================",
    "-- Vio ♡ — DATABASE UPDATE (generated by `npm run db:bundle`)",
    "-- For projects set up with an older supabase/setup.sql: paste everything",
    "-- into Supabase → SQL Editor → Run. Safe to run more than once.",
    `-- Includes: ${files.join(", ")}`,
    "-- =====================================================================",
    "",
  ];
  for (const f of files) {
    parts.push(`-- ---------------------------------------------------------------------`, `-- ${f}`, `-- ---------------------------------------------------------------------`, readFileSync(path.join(dir, f), "utf8").trim(), "");
  }
  return parts.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  writeFileSync(path.join(root, "supabase", "setup.sql"), buildSetupSql());
  writeFileSync(path.join(root, "supabase", "update.sql"), buildUpdateSql());
  console.log("supabase/setup.sql + supabase/update.sql updated ✓");
}
